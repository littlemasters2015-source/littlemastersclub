	<h1>About</h1>
	<p>
		Little Masters Club is a 501(c)(3) nonprofit organization that seeks to provide an encouraging
		environment for kids to be learners, mentors, team players, and leaders. We promote “learning by
		doing” through a multitude of fun projects. Our goal is to connect children to their community,
		invoke their compassion and motivation, develop their skills through our projects, and give them
		an opportunity to shine.
	</p>
	<p>
		We know children learn better when they’re interested in the subject, with their friends, and
		have confidence and support. Little Masters Club designs projects to be heavily team based, with
		as little adult intervention as possible. The community will always be there for a helping hand,
		but kids are encouraged to lead projects, teach peers, work together, and mentor children
		younger than them as much as they can. We provide a safe and fun environment to try, fail, try
		again, fail harder, and finally succeed! There is no better motivator than hard earned success.
	</p>
	<p>
		Our vision is to see children discover their potential and develop the skills necessary to be
		successful adults. A strong community and meaningful support are fundamental building blocks of
		happiness. We strive to create just that for our kids to flourish in and become well-rounded
		individuals.
	</p>
	<h2>Our Goals</h2>
	<p>We aim to help our children grow their sense of:</p>
	<ul>
		<li>Commitment</li>
		<li>Responsibility</li>
		<li>Leadership</li>
		<li>Teamwork</li>
		<li>Compassion</li>
		<li>Persistence</li>
	</ul>
	<p>We also aim at providing opportunities for parents to:</p>
	<ul>
		<li>Grow together with their children</li>
		<li>Share their passion</li>
		<li>Network with fellow families</li>
	</ul>
	<h2>Community-Driven</h2>
	<p>
		Ideas count! At Little Masters Club, everyone can initiate ideas and run projects based on his
		or her interests or specialties. Our projects are highly involved by both parents and kids.
		Parents initiate a program and set up the environment to support. Kids lead and implement the
		program.
	</p>
	<h2>Linkage to China</h2>
	<p>
		Little Masters Club has strong linkage to China. We have branches in Beijing, JingDeZhen,
		Shenzhen. This offers a great opportunity for learning Chinese culture and building
		relationships with someone in China. We run many programs related to China, examples include
		GEST ( Gansu Education Support Team), Online Teaching, Community Study of Chinese Rural Regions.
	</p>
	<h2>Why Join?</h2>
	<ul>
		<li>Learn international culture in a relaxing and encouraging environment</li>
		<li>Practice leadership, cooperation, mentoring, and other social skills in a group setting</li>
		<li>Network with people across communities</li>
		<li>Get opportunities to lead projects and other teammates</li>
		<li>Share personal interests and passions</li>
	</ul>
	<h2>Our Team</h2>
	<p>
		The core team of Little Masters Club consists of two parts: the board of directors and the
		project leaders. The board of directors provide the guidance and infrastructure to enable the
		platform for parents and kids to develop and carry out their projects to their full potential.
		The driving engine of the club is the project leaders. These group of people lead the
		corresponding teams to transform their ideas into reality. They are the ones who make the Little
		Masters Club distinguish itself from others.
	</p>
