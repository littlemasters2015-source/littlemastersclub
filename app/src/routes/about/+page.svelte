	<h1>About Us</h1>
	<h2>Who We Are</h2>
	<p>
		Little Masters Club (LMC) is a 501(c)(3) non-profit organization that seeks to provide an
		encouraging environment and open platform for kids to be learners, mentors, team players, and
		leaders. Our goal is to invoke the kids’ passion of serving our community, build up their
		leadership and teamwork skills, and encourage them to flourish in a multicultural society.
	</p>
	<h2>What We Do</h2>
	<p>
		LMC projects are led by kids with adult guidance as needed. Our projects vary from community
		service, extra-curriculum activities, education support to traditional culture exploration. We
		encourage all kids to be creative and come up with their own ideas of how to contribute to the
		community. Whether it’s creating art, spreading knowledge, exchanging culture, or fundraising
		for a good cause, we’re making it happen! Through our variety of accessible opportunities, kids
		explore their interests with friends, mentor younger members, and discover their full potential
		to make things possible.
	</p>
</div>
